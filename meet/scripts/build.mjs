import { readFile, writeFile, mkdir, readdir, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const publicDir = path.join(root, 'public');
const mime = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.svg': 'image/svg+xml', '.txt': 'text/plain; charset=utf-8', '.json': 'application/json; charset=utf-8', '.mjs': 'text/javascript; charset=utf-8' };
const assets = {};
for (const name of (await readdir(publicDir)).sort()) {
  const ext = path.extname(name);
  if (!mime[ext]) continue;
  assets[`/${name}`] = { body: await readFile(path.join(publicDir, name), 'utf8'), type: mime[ext] };
}
if (!assets['/index.html'] || !assets['/app.js'] || !assets['/styles.css']) throw new Error('Missing frontend assets');
try {
  assets['/agent.mjs'] = { body: await readFile(path.join(root, 'cli/agent.mjs'), 'utf8'), type: mime['.mjs'] };
} catch (e) { if (e.code !== 'ENOENT') throw e; }
await mkdir(path.join(root, 'src'), { recursive: true });
await mkdir(path.join(root, 'dist'), { recursive: true });
await writeFile(path.join(root, 'src/assets.js'), `// Generated by scripts/build.mjs. Do not edit.\nexport const ASSETS = ${JSON.stringify(assets)};\n`);
for (const name of ['worker.js', 'room.js', 'assets.js']) await copyFile(path.join(root, 'src', name), path.join(root, 'dist', name));
console.log(`Built ${Object.keys(assets).length} static assets and 3 Worker modules.`);
